func TestRoomInvitationLifecycle(t *testing.T) {
	c, _ := setupTestCore(t)
	ctx := testContext(t)
	sender, err := c.CreateUser(ctx, SystemActorID, "inviter", "Inviter", "password123")
	require.NoError(t, err)
	recipient, err := c.CreateUser(ctx, SystemActorID, "invitee", "Invitee", "password123")
	require.NoError(t, err)
	room, err := c.CreateRoom(ctx, sender.Id, KindChannel, "", "private", "Private")
	require.NoError(t, err)
	_, err = c.JoinRoom(ctx, sender.Id, KindChannel, sender.Id, room.Id)
	require.NoError(t, err)
	joinedView, err := c.RoomDirectoryReads().GetRoom(ctx, sender.Id, room.Id)
	require.NoError(t, err)
	require.False(t, joinedView.ViewerState.CanJoinRoom)
	require.True(t, joinedView.ViewerState.CanRejoin)
	_, err = c.RoomInvitations().Create(ctx, sender.Id, room.Id, recipient.Id)
	require.ErrorIs(t, err, ErrPermissionDenied)
	require.NoError(t, c.GrantUserRoomPermission(ctx, SystemActorID, room.Id, sender.Id, PermRoomInvite))
	require.NoError(t, c.DenyRoomPermission(ctx, SystemActorID, room.Id, RoleEveryone, PermRoomJoin))
	require.NoError(t, c.DenyRoomPermission(ctx, SystemActorID, room.Id, RoleEveryone, PermRoomList))
	require.NoError(t, c.DenyRoomPermission(ctx, SystemActorID, room.Id, RoleEveryone, PermMessageRead))
	invitation, err := c.RoomInvitations().Create(ctx, sender.Id, room.Id, recipient.Id)
	require.NoError(t, err)
	again, err := c.RoomInvitations().Create(ctx, sender.Id, room.Id, recipient.Id)
	require.NoError(t, err)
	require.Equal(t, invitation, again)
	dir, err := c.RoomDirectoryReads().GetRoom(ctx, recipient.Id, room.Id)
	require.NoError(t, err)
	require.NotNil(t, dir.ViewerState.Invitation)
	require.False(t, dir.ViewerState.IsMember)
	require.False(t, dir.ViewerState.CanReadMessages)
	require.True(t, dir.ViewerState.CanAcceptInvitation)
	_, err = c.RoomInvitations().Respond(ctx, sender.Id, invitation.ID, true)
	require.ErrorIs(t, err, ErrPermissionDenied)
	require.NoError(t, c.DenyUserRoomPermission(ctx, SystemActorID, room.Id, sender.Id, PermRoomInvite))
	_, err = c.RoomInvitations().Respond(ctx, recipient.Id, invitation.ID, true)
	require.ErrorIs(t, err, ErrPermissionDenied)
	require.NoError(t, c.GrantUserRoomPermission(ctx, SystemActorID, room.Id, sender.Id, PermRoomInvite))
	accepted, err := c.RoomInvitations().Respond(ctx, recipient.Id, invitation.ID, true)
	require.NoError(t, err)
	require.Equal(t, "accepted", accepted.Status)
	member, err := c.RoomMembershipExists(ctx, KindChannel, recipient.Id, room.Id)
	require.NoError(t, err)
	require.True(t, member)
	canRead, err := c.CanReadMessages(ctx, recipient.Id, KindChannel, room.Id)
	require.NoError(t, err)
	require.False(t, canRead)
	joinedView, err = c.RoomDirectoryReads().GetRoom(ctx, recipient.Id, room.Id)
	require.NoError(t, err)
	require.False(t, joinedView.ViewerState.CanRejoin)
	require.NoError(t, c.LeaveRoom(ctx, recipient.Id, KindChannel, recipient.Id, room.Id))
	_, err = c.RoomInvitations().Respond(ctx, recipient.Id, invitation.ID, true)
	require.NoError(t, err)
	member, err = c.RoomMembershipExists(ctx, KindChannel, recipient.Id, room.Id)
	require.NoError(t, err)
	require.False(t, member)
	facts, _, err := c.EventPublisher.SubjectEvents(ctx, evtstream.RoomAggregate(room.Id).Subject(evtstream.EventRoomInvitationAccepted))
	require.NoError(t, err)
	require.Len(t, facts, 1)
	require.Equal(t, recipient.Id, facts[0].ActorId)
}

func TestRoomInvitationConcurrentResponse(t *testing.T) {
	c, _ := setupTestCore(t)
	ctx := testContext(t)
	sender, err := c.CreateUser(ctx, SystemActorID, "sender", "Sender", "password123")
	require.NoError(t, err)
	recipient, err := c.CreateUser(ctx, SystemActorID, "recipient", "Recipient", "password123")
	require.NoError(t, err)
	room, err := c.CreateRoom(ctx, sender.Id, KindChannel, "", "race", "Race")
	require.NoError(t, err)
	_, err = c.JoinRoom(ctx, sender.Id, KindChannel, sender.Id, room.Id)
	require.NoError(t, err)
	require.NoError(t, c.GrantUserRoomPermission(ctx, SystemActorID, room.Id, sender.Id, PermRoomInvite))
	v, err := c.RoomInvitations().Create(ctx, sender.Id, room.Id, recipient.Id)
	require.NoError(t, err)
	var wg sync.WaitGroup
	for _, accept := range []bool{true, false} {
		wg.Go(func() { _, _ = c.RoomInvitations().Respond(ctx, recipient.Id, v.ID, accept) })
	}
	wg.Wait()
	v, err = c.RoomInvitations().Get(ctx, recipient.Id, v.ID)
	require.NoError(t, err)
	require.Contains(t, []string{"accepted", "declined"}, v.Status)
	member, err := c.RoomMembershipExists(ctx, KindChannel, recipient.Id, room.Id)
	require.NoError(t, err)
	require.Equal(t, v.Status == "accepted", member)
}

func TestRoomInvitationProjectionExpiryAndReplay(t *testing.T) {
	now := time.Now()
	p := NewRoomInvitationProjection()
	event := newEvent("sender", &evtv1.Event{Event: &evtv1.Event_RoomInvitationCreated{RoomInvitationCreated: &evtv1.RoomInvitationCreatedEvent{RoomId: "room", InvitationId: "invitation", RecipientId: "recipient", ExpiresAt: timestamppb.New(now.Add(time.Hour))}}})
	require.NoError(t, p.Apply(event, 1))
	v, ok := p.pending("room", "recipient", now)
	require.True(t, ok)
	require.Equal(t, "sender", v.SenderID)
	_, ok = p.pending("room", "recipient", now.Add(time.Hour))
	require.False(t, ok)
	require.NoError(t, p.Apply(newEvent("recipient", &evtv1.Event{Event: &evtv1.Event_RoomInvitationDeclined{RoomInvitationDeclined: &evtv1.RoomInvitationDeclinedEvent{RoomId: "room", InvitationId: "invitation", RecipientId: "recipient", SenderId: "sender"}}}), 2))
	v, ok = p.get("invitation")
	require.True(t, ok)
	require.Equal(t, "declined", v.Status)
}

func TestRoomInvitationRealtimeRecipientWithoutMembership(t *testing.T) {
	c, _ := setupTestCore(t)
	ctx := testContext(t)
	sender, err := c.CreateUser(ctx, SystemActorID, "replay-sender", "Sender", "password123")
	require.NoError(t, err)
	recipient, err := c.CreateUser(ctx, SystemActorID, "replay-recipient", "Recipient", "password123")
	require.NoError(t, err)
	outsider, err := c.CreateUser(ctx, SystemActorID, "replay-outsider", "Outsider", "password123")
	require.NoError(t, err)
	room, err := c.CreateRoom(ctx, sender.Id, KindChannel, "", "replay-room", "Private")
	require.NoError(t, err)
	_, err = c.JoinRoom(ctx, sender.Id, KindChannel, sender.Id, room.Id)
	require.NoError(t, err)
	require.NoError(t, c.GrantUserRoomPermission(ctx, SystemActorID, room.Id, sender.Id, PermRoomInvite))
	require.NoError(t, c.DenyRoomPermission(ctx, SystemActorID, room.Id, RoleEveryone, PermRoomList))
	before, err := c.PlanRealtimeReplay(ctx, recipient.Id, "")
	require.NoError(t, err)
	outsideBefore, err := c.PlanRealtimeReplay(ctx, outsider.Id, "")
	require.NoError(t, err)
	v, err := c.RoomInvitations().Create(ctx, sender.Id, room.Id, recipient.Id)
	require.NoError(t, err)
	plan, err := c.PlanRealtimeReplay(ctx, recipient.Id, before.BoundaryCursor)
	require.NoError(t, err)
	require.False(t, plan.Reset)
	require.Len(t, plan.Events, 1)
	require.Equal(t, v.ID, plan.Events[0].EVTEvent().GetRoomInvitationCreated().InvitationId)
	facts, seq, err := c.EventPublisher.SubjectEvents(ctx, evtstream.RoomAggregate(room.Id).Subject(evtstream.EventRoomInvitationCreated))
	require.NoError(t, err)
	for _, user := range []string{sender.Id, recipient.Id, outsider.Id} {
		_, visible := c.myEventsModel.filterReadyEVTRoomSubjectEvent(ctx, user, map[string]struct{}{}, room.Id, facts[0], seq)
		require.Equal(t, user != outsider.Id, visible)
	}
	outside, err := c.PlanRealtimeReplay(ctx, outsider.Id, outsideBefore.BoundaryCursor)
	require.NoError(t, err)
	for _, e := range outside.Events {
		require.Nil(t, e.EVTEvent().GetRoomInvitationCreated())
	}
}

// A second and a newly started replica must use EVT, not a sender-local cache.
func TestRoomInvitationReplicaRecovery(t *testing.T) {
	ns, _ := testutil.StartNATS(t)
	cfg := config.CoreConfig{SecretKey: "room-invitation-replica-secret", Assets: config.AssetsConfig{SigningSecret: "room-invitation-signing-secret"}}
	first := startReplica(t, ns, cfg)
	second := startReplica(t, ns, cfg)
	ctx := testContext(t)
	sender, err := first.CreateUser(ctx, SystemActorID, "replica-sender", "Sender", "password123")
	require.NoError(t, err)
	recipient, err := first.CreateUser(ctx, SystemActorID, "replica-recipient", "Recipient", "password123")
	require.NoError(t, err)
	room, err := first.CreateRoom(ctx, sender.Id, KindChannel, "", "replica-room", "")
	require.NoError(t, err)
	_, err = first.JoinRoom(ctx, sender.Id, KindChannel, sender.Id, room.Id)
	require.NoError(t, err)
	require.NoError(t, first.GrantUserRoomPermission(ctx, SystemActorID, room.Id, sender.Id, PermRoomInvite))
	invite, err := first.RoomInvitations().Create(ctx, sender.Id, room.Id, recipient.Id)
	require.NoError(t, err)
	duplicate, err := second.RoomInvitations().Create(ctx, sender.Id, room.Id, recipient.Id)
	require.NoError(t, err)
	require.Equal(t, invite.ID, duplicate.ID)
	recovered := startReplica(t, ns, cfg)
	pending, err := recovered.RoomInvitations().Get(ctx, recipient.Id, invite.ID)
	require.NoError(t, err)
	require.Equal(t, invite, pending)
	_, err = second.RoomInvitations().Respond(ctx, recipient.Id, invite.ID, true)
	require.NoError(t, err)
	accepted, err := recovered.RoomInvitations().Get(ctx, recipient.Id, invite.ID)
	require.NoError(t, err)
	require.Equal(t, "accepted", accepted.Status)
	member, err := recovered.RoomMembershipExists(ctx, KindChannel, recipient.Id, room.Id)
	require.NoError(t, err)
	require.True(t, member)
}

