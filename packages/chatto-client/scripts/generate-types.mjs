// Generate the re-exports of @chatto/api-types in src/types.ts and
// src/types/admin.ts. Run after the public protocol gains or loses a module:
//   node scripts/generate-types.mjs
// With --check, fail instead when the files are out of date; the package's
// check script does this.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const generated = new URL('../../api-types/src/chatto/', import.meta.url);

/** Module specifiers of `@chatto/api-types` for the given protocol packages. */
export function typeModules(packages) {
  return packages.flatMap((name) =>
    readdirSync(new URL(`${name}/v1/`, generated))
      .filter((file) => file.endsWith('.ts') && !file.endsWith('.d.ts'))
      .sort()
      // api-types exports admin, api, and realtime directly and the others under chatto/.
      .map((file) => {
        const path = ['admin', 'api', 'realtime'].includes(name) ? name : `chatto/${name}`;
        return `@chatto/api-types/${path}/v1/${file.slice(0, -3)}`;
      })
  );
}

/** The source of a module that re-exports `modules`. */
export function reexports(description, modules) {
  return [
    '/**',
    ...description.map((line) => ` * ${line}`.trimEnd()),
    ' *',
    ' * Generated by scripts/generate-types.mjs; do not edit.',
    ' */',
    '',
    ...modules.map((module) => `export * from '${module}';`),
    ''
  ].join('\n');
}

export const publicTypes = () =>
  reexports(
    [
      "Messages and services of Chatto's public protocol: the API, realtime,",
      'discovery, and authentication packages of `@chatto/api-types`.'
    ],
    typeModules(['api', 'realtime', 'discovery', 'auth'])
  );

export const adminTypes = () =>
  reexports(["Messages and services of Chatto's administration API."], typeModules(['admin']));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = [
    [new URL('../src/types.ts', import.meta.url), publicTypes()],
    [new URL('../src/types/admin.ts', import.meta.url), adminTypes()]
  ];
  if (process.argv.includes('--check')) {
    const stale = outputs.filter(([file, source]) => readFileSync(file, 'utf8') !== source);
    for (const [file] of stale) console.error(`${fileURLToPath(file)} is out of date`);
    if (stale.length) {
      console.error('Run: node scripts/generate-types.mjs');
      process.exit(1);
    }
  } else {
    for (const [file, source] of outputs) writeFileSync(file, source);
  }
}
