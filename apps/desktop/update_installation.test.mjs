import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import test from 'node:test';
import { windowsInstallerConfig } from './scripts/windows-installer-config.mjs';
import { hasWindowsUninstaller } from './update_installation.mjs';

test('update eligibility recognizes the uninstaller generated by electron-builder', async () => {
  const require = createRequire(import.meta.url);
  const builderRequire = createRequire(require.resolve('electron-builder'));
  const { AppInfo } = builderRequire('app-builder-lib/out/appInfo.js');
  const config = windowsInstallerConfig('0.5.0-beta.24');
  const appInfo = new AppInfo({ metadata: { version: '0.5.0-beta.24' }, config });
  const template = await readFile(
    builderRequire.resolve('app-builder-lib/templates/nsis/common.nsh'),
    'utf8'
  );
  const uninstallerPattern = template.match(/^!define UNINSTALL_FILENAME "(.+)"$/m)?.[1];
  assert.ok(uninstallerPattern, 'NSIS must define its uninstaller filename');
  const uninstaller = uninstallerPattern.replace('${PRODUCT_FILENAME}', appInfo.productFilename);
  const scratch = new URL('../../.context/', import.meta.url);
  await mkdir(scratch, { recursive: true });
  const directory = await mkdtemp(new URL('windows-update-test-', scratch));
  try {
    const executable = path.join(directory, 'chatto-desktop.exe');
    await writeFile(executable, '');
    assert.equal(hasWindowsUninstaller(executable), false, 'ZIP copies cannot auto-update');
    await writeFile(path.join(directory, uninstaller), '');
    assert.equal(hasWindowsUninstaller(executable), true, 'NSIS installs can auto-update');
    await rm(path.join(directory, uninstaller));
    assert.equal(hasWindowsUninstaller(executable), false);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});
