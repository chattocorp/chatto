const botAPIKeySecretBytes = 16

const (
	idAlphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
	idLength   = 14
)

// newID generates a new unique ID using NanoID with the given prefix.
func newID(prefix string) string {
	id, err := gonanoid.Generate(idAlphabet, idLength)
	if err != nil {
		log.Fatal("Failed to generate ID", "error", err)
	}
	return prefix + id
}

// NewUserID generates a new user ID with "U" prefix.
func NewUserID() string {
	return newID("U")
}

// isCanonicalUserID reports whether id has the exact shape generated by
// NewUserID. This is intentionally stricter than merely checking that an ID is
// safe to interpolate into a NATS subject.
func isCanonicalUserID(id string) bool {
	if len(id) != idLength+1 || id[0] != 'U' {
		return false
	}
	for i := 1; i < len(id); i++ {
		if !strings.ContainsRune(idAlphabet, rune(id[i])) {
			return false
		}
	}
	return true
}

