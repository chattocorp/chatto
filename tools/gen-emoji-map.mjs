#!/usr/bin/env node

/**
 * Generates maps from gemoji, supplemental entries, and Unicode Emoji 15.0 tones.
 * This ensures the Go backend uses the same emoji data as the frontend,
 * preventing version mismatches where newer emojis work in the picker
 * but fail validation on the backend.
 *
 * Run via: mise codegen-emoji
 */

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { format, resolveConfig } from 'prettier';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Resolve gemoji from the frontend workspace package.
const require = createRequire(resolve(__dirname, '../apps/frontend/package.json'));
const { gemoji } = require('gemoji');
// Supplement the released gemoji catalog without changing established aliases.
const additions = JSON.parse(readFileSync(resolve(__dirname, 'emoji-additions.json'), 'utf8'));
const existingNames = new Set(gemoji.flatMap((entry) => entry.names));
for (const entry of additions) {
  for (const name of entry.names) {
    if (existingNames.has(name)) throw new Error(`Duplicate emoji name: ${name}`);
    existingNames.add(name);
  }
}
const catalog = [...gemoji, ...additions];
const additionsPath = resolve(
  __dirname,
  '../packages/chatto-client/src/messaging/emojiAdditions.gen.ts'
);
writeFileSync(
  additionsPath,
  await format(
    `// Generated by tools/gen-emoji-map.mjs. DO NOT EDIT.\n` +
      `import type { Gemoji } from 'gemoji';\n` +
      `/** Built-in entries not yet included in the released gemoji catalog. */\n` +
      `export const emojiAdditions: Gemoji[] = ${JSON.stringify(additions)};\n`,
    { ...(await resolveConfig(additionsPath)), parser: 'typescript' }
  )
);

const outputPath = resolve(__dirname, '../cli/internal/core/emoji_gen.go');

// Build name → emoji entries (each emoji can have multiple names/aliases)
const entries = [];
for (const e of catalog) {
  for (const name of e.names) {
    entries.push([name, e.emoji]);
  }
}

// Use Unicode's complete sequences. Inserting a modifier into an arbitrary
// base breaks ZWJ sequences and cannot represent mixed-tone couples.
const unicodeRecords = readFileSync(resolve(__dirname, 'unicode/emoji-test.txt'), 'utf8')
  .split('\n')
  .flatMap((line) => {
    const match = line.match(/^([0-9A-F ]+)\s*; fully-qualified\s*# \S+ E[\d.]+ (.+)$/);
    return match
      ? [
          {
            emoji: String.fromCodePoint(
              ...match[1]
                .trim()
                .split(/\s+/)
                .map((n) => parseInt(n, 16))
            ),
            description: match[2]
          }
        ]
      : [];
  });
const normalize = (emoji) => emoji.replaceAll('\uFE0F', '');
const namesByEmoji = new Map(catalog.map((e) => [normalize(e.emoji), e.names]));
const namesByDescription = new Map(
  unicodeRecords.map((e) => [e.description, namesByEmoji.get(normalize(e.emoji))])
);
const skinToneEntries = [];
for (const record of unicodeRecords) {
  const tones = [...record.emoji.matchAll(/[\u{1F3FB}-\u{1F3FF}]/gu)].map(
    (m) => m[0].codePointAt(0) - 0x1f3f9
  );
  if (tones.length === 0) continue;
  // Unicode descriptions retain the base name when tone annotations are removed.
  const description = record.description
    .replace(/(?:light|medium-light|medium|medium-dark|dark) skin tone/g, '')
    .replace(/: , /g, ': ')
    .replace(/, , /g, ', ')
    .replace(/(?:[:,] )+$/, '');
  const names = namesByDescription.get(description);
  if (!names) continue;
  const suffix = `::skin-tone-${(new Set(tones).size === 1 ? [tones[0]] : tones).join('-')}`;
  for (const name of names) skinToneEntries.push([name + suffix, record.emoji]);
}
entries.push(...skinToneEntries);
const clientOutputPath = resolve(
  __dirname,
  '../packages/chatto-client/src/messaging/emojiSkinTones.gen.ts'
);
writeFileSync(
  clientOutputPath,
  await format(
    `// Generated by tools/gen-emoji-map.mjs from Unicode Emoji 15.0. DO NOT EDIT.\n` +
      `/** Complete Unicode skin-tone sequences, keyed by Slack-style reaction name. */\n` +
      `export const emojiSkinTones: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(skinToneEntries), null, 2)};\n`,
    { ...(await resolveConfig(clientOutputPath)), parser: 'typescript' }
  )
);

// Sort for deterministic output
entries.sort((a, b) => a[0].localeCompare(b[0]));

// Generate Go source
const goEntries = entries.map(([name, emoji]) => {
  // Escape backslashes and quotes in name (shouldn't occur in practice)
  const safeName = name.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return `\t"${safeName}": "${emoji}",`;
});

const goSource = `// Code generated by tools/gen-emoji-map.mjs. DO NOT EDIT.

package core

// emojiNameToUnicode maps emoji shortcode names to their Unicode representations.
// Generated from gemoji, supplemental entries, and Unicode Emoji 15.0 skin-tone sequences.
// Total entries: ${entries.length} (including aliases)
var emojiNameToUnicode = map[string]string{
${goEntries.join('\n')}
}
`;

writeFileSync(outputPath, goSource);
execFileSync('gofmt', ['-w', outputPath]);
// Python platform converters use the same names without parsing Go source.
writeFileSync(
  resolve(__dirname, 'emoji-map.json'),
  JSON.stringify(Object.fromEntries(entries), null, 2) + '\n'
);
console.log(`Generated ${outputPath} with ${entries.length} emoji entries`);
