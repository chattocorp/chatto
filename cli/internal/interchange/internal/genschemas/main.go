// Command genschemas embeds the authoritative repository schemas in the CLI.
// Run it with go generate from internal/interchange.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	var output bytes.Buffer
	output.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage interchange\n\nvar schemaJSON = map[string]string{\n")
	for _, name := range []string{"asset", "common", "event", "manifest", "room", "user"} {
		raw, err := os.ReadFile(filepath.Join("../../../schema/interchange/v1", name+".schema.json"))
		if err != nil {
			return err
		}
		var compact bytes.Buffer
		if err := json.Compact(&compact, raw); err != nil {
			return err
		}
		fmt.Fprintf(&output, "%q: %q,\n", name, compact.String())
	}
	output.WriteString("}\n")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("schemas_generated.go", formatted, 0644)
}
